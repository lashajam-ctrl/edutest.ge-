-- 5) Create/update profile on Auth signup and create under-16 guardian request server-side.
create or replace function public.handle_edutest_new_user()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_role text;
  v_birth date;
  v_guardian text;
  v_consent_version text;
begin
  begin
    v_birth := nullif(new.raw_user_meta_data ->> 'birth_date','')::date;
  exception when others then
    v_birth := null;
  end;
  v_guardian := lower(trim(coalesce(new.raw_user_meta_data ->> 'guardian_email','')));
  v_consent_version := coalesce(nullif(new.raw_user_meta_data ->> 'guardian_consent_version',''),'guardian-consent-v1');
  v_role := case
    when new.raw_user_meta_data ->> 'requested_role' = 'teacher' then 'pending_teacher'
    when new.raw_user_meta_data ->> 'requested_role' = 'guardian' then 'guardian'
    else 'student'
  end;

  insert into public.profiles(
    id,email,name,role,grade,school,birth_date,guardian_email,
    terms_version,terms_accepted_at,privacy_version,privacy_acknowledged_at,last_active_at
  ) values (
    new.id,new.email,coalesce(new.raw_user_meta_data ->> 'name',''),v_role,
    coalesce(new.raw_user_meta_data ->> 'grade',''),coalesce(new.raw_user_meta_data ->> 'school',''),
    v_birth,nullif(v_guardian,''),
    nullif(new.raw_user_meta_data ->> 'terms_version',''),now(),
    nullif(new.raw_user_meta_data ->> 'privacy_version',''),now(),now()
  )
  on conflict (id) do update set
    email=excluded.email,name=excluded.name,grade=excluded.grade,school=excluded.school,
    birth_date=coalesce(public.profiles.birth_date,excluded.birth_date),
    guardian_email=coalesce(public.profiles.guardian_email,excluded.guardian_email),
    updated_at=now();

  if v_role='student' and v_birth is not null and v_birth > (current_date - interval '16 years')::date then
    if v_guardian='' then
      raise exception 'Guardian email is required for a student under 16';
    end if;
    insert into public.guardian_consent_requests(child_user_id,child_display_name,guardian_email,consent_version,status)
    values(new.id,coalesce(new.raw_user_meta_data ->> 'name',''),v_guardian,v_consent_version,'pending')
    on conflict do nothing;
    insert into public.guardian_consent_log(child_user_id,guardian_email,action,consent_version)
    values(new.id,v_guardian,'requested',v_consent_version);
  end if;
  return new;
end;
$$;
revoke all on function public.handle_edutest_new_user() from public;

drop trigger if exists on_auth_user_created_edutest on auth.users;
create trigger on_auth_user_created_edutest after insert on auth.users
for each row execute function public.handle_edutest_new_user();

-- 6) Existing/legacy students must complete age verification before learning history is available.
create or replace function public.complete_age_verification(
  p_birth_date date,
  p_guardian_email text,
  p_terms_version text,
  p_privacy_version text,
  p_guardian_consent_version text
) returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_under16 boolean;
  v_email text := lower(trim(coalesce(p_guardian_email,'')));
  v_name text;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if p_birth_date is null or p_birth_date > current_date or p_birth_date < date '1900-01-01' then
    raise exception 'Invalid birth date';
  end if;
  select name into v_name from public.profiles where id=v_uid and role='student';
  if not found then raise exception 'Student profile not found'; end if;
  v_under16 := p_birth_date > (current_date - interval '16 years')::date;
  if v_under16 and (v_email='' or v_email=lower(coalesce(auth.jwt()->>'email',''))) then
    raise exception 'A different guardian email is required for a student under 16';
  end if;

  update public.profiles set
    birth_date=p_birth_date,
    guardian_email=case when v_under16 then v_email else null end,
    guardian_verified_at=case when v_under16 then null else guardian_verified_at end,
    terms_version=p_terms_version,terms_accepted_at=now(),
    privacy_version=p_privacy_version,privacy_acknowledged_at=now(),
    updated_at=now(),last_active_at=now()
  where id=v_uid;

  if v_under16 then
    update public.guardian_consent_requests set status='superseded',updated_at=now()
      where child_user_id=v_uid and status='pending';
    insert into public.guardian_consent_requests(child_user_id,child_display_name,guardian_email,consent_version,status)
      values(v_uid,v_name,v_email,p_guardian_consent_version,'pending');
    insert into public.guardian_consent_log(child_user_id,guardian_email,action,consent_version)
      values(v_uid,v_email,'requested',p_guardian_consent_version);
  end if;
  return jsonb_build_object('under16',v_under16,'guardian_email',case when v_under16 then v_email else null end);
end;
$$;
revoke all on function public.complete_age_verification(date,text,text,text,text) from public;
grant execute on function public.complete_age_verification(date,text,text,text,text) to authenticated;

-- 7) Guardian acceptance / decline / withdrawal. The guardian must be authenticated as the same email
-- that the child supplied; acceptance time is server-generated.
create or replace function public.accept_guardian_consent(p_child_user_id uuid,p_consent_version text)
returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  v_guardian_uid uuid := auth.uid();
  v_guardian_email text := lower(coalesce(auth.jwt()->>'email',''));
  v_req public.guardian_consent_requests%rowtype;
begin
  if v_guardian_uid is null or v_guardian_email='' then raise exception 'Authentication required'; end if;
  select * into v_req from public.guardian_consent_requests
   where child_user_id=p_child_user_id
     and lower(guardian_email)=v_guardian_email
     and status='pending'
   order by requested_at desc limit 1 for update;
  if not found then raise exception 'No matching pending guardian-consent request'; end if;
  if v_req.consent_version <> p_consent_version then raise exception 'Consent text version mismatch'; end if;

  update public.guardian_consent_requests set status='accepted',guardian_user_id=v_guardian_uid,
    accepted_at=now(),updated_at=now() where id=v_req.id;
  update public.profiles set guardian_verified_at=now(),updated_at=now() where id=p_child_user_id;
  insert into public.guardian_consent_log(child_user_id,guardian_user_id,guardian_email,action,consent_version)
    values(p_child_user_id,v_guardian_uid,v_guardian_email,'accepted',p_consent_version);
  return true;
end;
$$;
revoke all on function public.accept_guardian_consent(uuid,text) from public;
grant execute on function public.accept_guardian_consent(uuid,text) to authenticated;

