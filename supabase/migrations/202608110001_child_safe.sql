create or replace function public.withdraw_guardian_consent(p_child_user_id uuid,p_consent_version text)
returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  v_uid uuid:=auth.uid(); v_email text:=lower(coalesce(auth.jwt()->>'email',''));
  v_req public.guardian_consent_requests%rowtype;
begin
  select * into v_req from public.guardian_consent_requests
   where child_user_id=p_child_user_id and lower(guardian_email)=v_email and status='accepted'
