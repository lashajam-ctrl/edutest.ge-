-- 9) Retention helper for application data. Schedule daily with Supabase Cron if desired.
-- Auth-user deletion must be done server-side (see included delete-account Edge Function).
create or replace function public.edutest_retention_cleanup()
returns table(question_rows_deleted bigint,subject_rows_deleted bigint,pending_requests_expired bigint)
language plpgsql security definer set search_path=''
as $$
declare qn bigint:=0; sn bigint:=0; gn bigint:=0;
begin
  delete from public.question_history q
    using public.profiles p
    where q.user_id=p.id and p.last_active_at < now()-interval '24 months';
  get diagnostics qn = row_count;
  delete from public.subject_history s
    using public.profiles p
    where s.user_id=p.id and p.last_active_at < now()-interval '24 months';
  get diagnostics sn = row_count;
  update public.guardian_consent_requests
    set status='superseded',updated_at=now()
    where status='pending' and requested_at < now()-interval '30 days';
  get diagnostics gn = row_count;
  return query select qn,sn,gn;
end; $$;
revoke all on function public.edutest_retention_cleanup() from public;

