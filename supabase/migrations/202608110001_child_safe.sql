-- 3) Account-level data-access guard. Student learning history is disabled until age is verified,
-- and for under-16 students until guardian consent has been verified.
create or replace function public.edutest_data_access_allowed(p_uid uuid)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = p_uid
      and p.deletion_requested_at is null
      and (
        p.role <> 'student'
        or (
          p.birth_date is not null
          and (
            p.birth_date <= (current_date - interval '16 years')::date
            or p.guardian_verified_at is not null
          )
        )
      )
  );
$$;
revoke all on function public.edutest_data_access_allowed(uuid) from public;
grant execute on function public.edutest_data_access_allowed(uuid) to authenticated;

