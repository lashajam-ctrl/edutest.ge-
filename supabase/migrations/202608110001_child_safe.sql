  update public.guardian_consent_requests set status='withdrawn',withdrawn_at=now(),updated_at=now() where id=v_req.id;
  update public.profiles set guardian_verified_at=null,updated_at=now() where id=p_child_user_id;
  insert into public.guardian_consent_log(child_user_id,guardian_user_id,guardian_email,action,consent_version)
    values(p_child_user_id,v_uid,v_email,'withdrawn',p_consent_version);
  return true;
end;
$$;
